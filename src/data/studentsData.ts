export const parseStudentsFromCSV = (csv: string): StudentRecord[] => {
  const lines = csv.trim().split('\n');
  const result: StudentRecord[] = [];

  for (let i = 1; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) continue;
    
    // Parse comma separated values handling possible quotes
    const parts = line.split(',');
    if (parts.length < 5) continue;

    let nisn = parts[0].trim().replace(/^['"]|['"]$/g, '');
    let nis = parts[1].trim().replace(/^['"]|['"]$/g, '');
    let name = parts[2].trim().replace(/^['"]|['"]$/g, '');
    let gender = (parts[3].trim().toUpperCase() === 'L' ? 'L' : 'P') as 'L' | 'P';
    let className = parts[4].trim().replace(/^['"]|['"]$/g, '');

    const id = `STD_${nisn || nis}_${i}`;

    result.push({
      id,
      nisn,
      nis,
      name,
      gender,
      className,
      rombel: className
    });
  }

  return result;
};

